"""Turn a pace-sim kernel folder (PE-YyXx, dm0..7, agu0..15) into the list of
32-bit host-bus writes that load it into pace_cgra, i.e. exactly what the
RISC-V driver does.  Also emits a C header for the firmware.

    python3 cgra_image.py <kernel_dir> <out.writes> [<out.h> <golden_dm_prefix>]
"""
import os, re, sys

PE_BASE, DM_BASE, CTL_BASE = 0x00000, 0x20000, 0x60000


def pe_addr(pe, region, off):           # region 0 CM, 1 AGU CM, 2 AGU ARF, 3 AGU MAX
    return PE_BASE | pe << 10 | region << 8 | off


def dm_addr(d, byte):
    return DM_BASE | (d // 4) << 16 | (d % 4) << 14 | byte


def bits_to_bytes(s):
    s = re.sub(r'\s', '', s)
    return bytes(int(s[i:i + 8], 2) for i in range(0, len(s), 8))


def parse_agu(txt):
    cm_part = txt.split('CM:')[1].split('ARF:')[0]
    arf_part = txt.split('ARF:')[1].split('MAX COUNT:')[0]
    maxc = int(txt.split('MAX COUNT:')[1].split()[0])
    insts = []
    for ln in cm_part.strip().splitlines():
        if not ln.strip():
            continue
        t, m, w, st = [x.strip() for x in ln.split(',')]
        b = (t == 'STORE') | (m == 'CONST') << 1 | {'B8': 0, 'B16': 1, 'B64': 2}[w] << 2 | int(st) << 4
        insts.append(b)
    arf = [int(x) for x in arf_part.split()]
    return insts, arf, maxc


def image(kdir):
    w = []
    for y in range(8):
        for x in range(8):
            raw = bits_to_bytes(open(os.path.join(kdir, f'PE-Y{y}X{x}')).read())
            for e in range(len(raw) // 8):
                word = int.from_bytes(raw[8 * e:8 * e + 8], 'little')
                w.append((pe_addr(y * 8 + x, 0, e << 3), word & 0xFFFFFFFF))
                w.append((pe_addr(y * 8 + x, 0, e << 3 | 4), word >> 32))
    for a in range(16):
        insts, arf, maxc = parse_agu(open(os.path.join(kdir, f'agu{a}')).read())
        pe = (a % 8) * 8 + (0 if a < 8 else 7)
        for i, b in enumerate(insts):
            w.append((pe_addr(pe, 1, i << 2), b))
        for i, v in enumerate(arf):
            w.append((pe_addr(pe, 2, i << 2), v))
        w.append((pe_addr(pe, 3, 0), (len(insts) - 1) << 24 | maxc))
    for d in range(8):
        raw = bits_to_bytes(open(os.path.join(kdir, f'dm{d}')).read())
        for i in range(0, len(raw), 4):
            v = int.from_bytes(raw[i:i + 4], 'little')
            if v:
                w.append((dm_addr(d, i), v))
    return w


def dm_checksums(prefix):
    """FNV-1a over each final DM (8 KB, as 32-bit little-endian words)."""
    sums = []
    for d in range(8):
        h = 0x811C9DC5
        for ln in open(f'{prefix}{d}'):
            v = int(ln, 16)
            for word in (v & 0xFFFFFFFF, v >> 32):
                h = ((h ^ word) * 0x01000193) & 0xFFFFFFFF
        sums.append(h)
    return sums


if __name__ == '__main__':
    kdir, out = sys.argv[1], sys.argv[2]
    w = image(kdir)
    with open(out, 'w') as f:
        for a, v in w:
            f.write(f'{a:05x} {v:08x}\n')
    if len(sys.argv) > 4:
        sums = dm_checksums(sys.argv[4])
        with open(sys.argv[3], 'w') as f:
            f.write(f'// generated by cgra_image.py from {os.path.basename(os.path.abspath(kdir))}\n')
            f.write(f'#define IMG_N {len(w)}\n')
            f.write('static const unsigned int img[IMG_N][2] = {\n')
            f.write(',\n'.join(f'  {{0x{a:05x}, 0x{v:08x}}}' for a, v in w) + '\n};\n')
            f.write('static const unsigned int dm_fnv_expected[8] = {'
                    + ', '.join(f'0x{s:08x}' for s in sums) + '};\n')
    print(f'{len(w)} host writes')
