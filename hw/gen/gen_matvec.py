"""Generate a hardwired-weight matrix-vector module.

For a weight matrix W (N x K, int4) this writes one Verilog file containing:
  <name>_rom : a constant ROM (a case statement) returning P columns of W per
               group index. Synthesis turns it into logic, not RAM: the
               weights become part of the circuit.
  <name>     : the ROM wired to a matvec_core instance.
"""
import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from model.ref import W_BITS, X_BITS, ACC_BITS, random_weights  # noqa: E402


def pack_group(w, g, p_par):
    """Pack columns g*P .. g*P+P-1 of w into one hex literal.
    Weight W[i][g*P+p] goes to nibble index p*N + i (nibble 0 = least significant)."""
    n = w.shape[0]
    nibbles = []
    for p in range(p_par):
        col = w[:, g * p_par + p]
        nibbles.extend(int(v) & 0xF for v in col)
    # Most significant nibble first in the hex string.
    return "".join(f"{v:x}" for v in reversed(nibbles))


CHUNK_HEX = 256  # 1024-bit pieces: simulators limit the length of one literal


def hex_literal(h):
    """A hex string as a Verilog literal, split into a {..} concatenation if long."""
    if len(h) <= CHUNK_HEX:
        return f"{len(h) * 4}'h{h}"
    parts = [h[i:i + CHUNK_HEX] for i in range(0, len(h), CHUNK_HEX)]
    return "{" + ", ".join(f"{len(s) * 4}'h{s}" for s in parts) + "}"


def emit_verilog(name, w, p_par):
    n, k = w.shape
    assert k % p_par == 0, "K must be a multiple of P"
    assert W_BITS == 4, "packing assumes 4-bit weights"
    groups = k // p_par
    gw = max(1, (groups - 1).bit_length()) if groups > 1 else 1
    bits = p_par * n * W_BITS

    lines = [
        f"// Generated by gen/gen_matvec.py: {name}, W is {n} x {k} int{W_BITS}, P={p_par}",
        f"module {name}_rom (",
        f"    input  wire [{gw-1}:0] grp,",
        f"    output reg  [{bits-1}:0] w",
        ");",
        "    always @* begin",
        "        case (grp)",
    ]
    for g in range(groups):
        lines.append(f"            {gw}'d{g}: w = {hex_literal(pack_group(w, g, p_par))};")
    lines += [
        f"            default: w = {bits}'d0;",
        "        endcase",
        "    end",
        "endmodule",
        "",
        f"module {name} (",
        "    input  wire clk,",
        "    input  wire rst,",
        "    input  wire start,",
        f"    input  wire [{k*X_BITS-1}:0] x,",
        "    output wire busy,",
        "    output wire done,",
        f"    output wire [{n*ACC_BITS-1}:0] y",
        ");",
        f"    wire [{gw-1}:0] grp;",
        f"    wire [{bits-1}:0] wgrp;",
        f"    {name}_rom rom (.grp(grp), .w(wgrp));",
        f"    matvec_core #(.N({n}), .K({k}), .P({p_par}), .XW({X_BITS}), .WW({W_BITS}), .AW({ACC_BITS})) core (",
        "        .clk(clk), .rst(rst), .start(start), .x(x),",
        "        .grp(grp), .wgrp(wgrp), .busy(busy), .done(done), .y(y)",
        "    );",
        "endmodule",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", required=True)
    ap.add_argument("--n", type=int, required=True, help="output features")
    ap.add_argument("--k", type=int, required=True, help="input features")
    ap.add_argument("--p", type=int, default=1, help="columns per cycle")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", type=Path, required=True, help="output directory")
    args = ap.parse_args()

    rng = np.random.default_rng(args.seed)
    w = random_weights(args.n, args.k, rng)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / f"{args.name}.v").write_text(emit_verilog(args.name, w, args.p))
    np.save(args.out / f"{args.name}_w.npy", w)


if __name__ == "__main__":
    main()
